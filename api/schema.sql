CREATE TABLE IF NOT EXISTS reports (
  id TEXT PRIMARY KEY, type TEXT NOT NULL, lon REAL NOT NULL, lat REAL NOT NULL, heading INTEGER,
  t INTEGER NOT NULL, exp INTEGER NOT NULL, up INTEGER NOT NULL DEFAULT 1, down INTEGER NOT NULL DEFAULT 0, ip TEXT
);
CREATE INDEX IF NOT EXISTS reports_exp ON reports(exp);
CREATE TABLE IF NOT EXISTS votes (id TEXT NOT NULL, ip TEXT NOT NULL, v INTEGER NOT NULL, PRIMARY KEY (id, ip));
